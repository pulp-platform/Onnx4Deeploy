def resolve_exporter(model_name: str):
    """
    Look up the exporter class + config from Onnx4Deeploy.list_available_models().
    Returns an instantiated exporter with config applied.
    """
    from Onnx4Deeploy import list_available_models

    models = list_available_models()
    key = next((k for k in models if k.lower() == model_name.lower()), None)
    if key is None:
        raise ValueError(f"Unknown model '{model_name}'. Known: {sorted(models.keys())}")
    info = models[key]
    cls = info["class"]
    exporter = cls(save_path="/tmp/_unused_make_single_step")
    # Inject overrides the same way Onnx4Deeploy.py does, so create_model() picks
    # up variant / num_classes / img_size etc.
    exporter._config_overrides = dict(info.get("config", {}))
    exporter.config = exporter.load_config()
    return exporter, info


def pytorch_param_to_onnx(name: str) -> str:
    """
    Convert a PyTorch named_parameters() key to its ONNX initializer name.

    PyTorch exposes the module hierarchy with '.' (e.g. 'fc1.weight',
    'bn_stem.weight', 'blocks.0.dw.weight').  Onnx4Deeploy's exporters flatten
    it to '_' (e.g. 'fc1_weight', 'bn_stem_weight', 'blocks_0_dw_weight').
    """
    return name.replace(".", "_")


def build_pytorch_loss(model_output: torch.Tensor, labels: torch.Tensor):
    """
    Pick the loss matching the model output / labels dtypes.

    - int64 labels  → CrossEntropyLoss (logits + class indices)
    - float labels  → MSELoss          (autoencoder-style reconstruction)
    """
    if labels.dtype == torch.int64:
        return torch.nn.functional.cross_entropy(
            model_output.reshape(model_output.shape[0], -1), labels.flatten()
        )
    return torch.nn.functional.mse_loss(model_output, labels)


def load_weights_into_pytorch(model: torch.nn.Module, init_map: dict) -> list[str]:
    """
    Copy ONNX initializer values into the matching PyTorch parameters.

    Returns the list of parameter names successfully loaded.
    """
    state = model.state_dict()
    loaded = []
    for pt_name in list(state.keys()):
        onnx_name = pytorch_param_to_onnx(pt_name)
        if onnx_name not in init_map:
            continue
        pt_tensor = state[pt_name]
        np_value = init_map[onnx_name]
        # Allow shape mismatch in the leading 1-D batch_dim that ORT sometimes
        # adds; reshape strict-equal to the target.
        if pt_tensor.shape != tuple(np_value.shape):
            try:
                np_value = np_value.reshape(tuple(pt_tensor.shape))
            except Exception:
                continue
        state[pt_name] = torch.from_numpy(np.asarray(np_value, dtype=np.float32).copy())
        loaded.append(pt_name)
    model.load_state_dict(state)
    return loaded


def synthesize_inputs(
    input_shape: tuple[int, ...], num_classes: int, seed: int
) -> tuple[np.ndarray, np.ndarray]:
    """Random Gaussian input + scalar int64 label (matches Onnx4Deeploy seed=42 default)."""
    rng = np.random.default_rng(seed)
    test_input = rng.standard_normal(size=input_shape, dtype=np.float32)
    labels = np.array([rng.integers(0, max(num_classes, 2))], dtype=np.int64)
    return test_input, labels


def synthesize_mse_target(input_shape: tuple[int, ...], seed: int) -> np.ndarray:
    """Reconstruction-style float target — same shape as input."""
    rng = np.random.default_rng(seed + 1)
    return rng.standard_normal(size=input_shape, dtype=np.float32)


