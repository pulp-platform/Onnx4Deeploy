# Test-data regeneration (PyTorch path)
# ---------------------------------------------------------------------------


def regenerate_test_data_pytorch(
    src_dir: Path,
    model_name: str,
    seed: int = 42,
) -> None:
    """
    Build inputs.npz / outputs.npz from PyTorch autograd (no ORT/com.microsoft).

    inputs.npz: every non-bool graph input keyed by name, in graph-input order
                — data, labels, params (loaded from network_infer.onnx),
                  grad-accumulation buffers (zeros).
    outputs.npz: 'loss' + each '<param>_grad.accumulation.out' keyed by graph
                 output name. Names must match the graph-output schema, since
                 testMVP feeds them positionally and per-tensor diff reporting
                 needs the names to be intelligible.
    """
    network_path = src_dir / "network.onnx"
    infer_path = src_dir / "network_infer.onnx"

    exporter, info = resolve_exporter(model_name)
    pt_model = exporter.create_model()
    pt_model.train()  # backward needs train mode for BN/Dropout to behave consistently

    if infer_path.exists():
        # Standard path: ONNX-side init weights are authoritative; load them
        # into PyTorch so the ref grads use the same starting point that
        # Deeploy will see baked into the deployed network.
        init_map = load_init_map(infer_path)
        loaded = load_weights_into_pytorch(pt_model, init_map)
        print(
            f"   loaded {len(init_map)} initializers from network_infer.onnx; "
            f"PyTorch absorbed {len(loaded)}/{sum(1 for _ in pt_model.named_parameters())} params"
        )
    else:
        # Vendored path: only network.onnx is available (no train/infer files
        # because they were dropped before vendoring). Use PyTorch's fresh
        # random weights as the source of truth — bake the same values into
        # ONNX initializers below so Deeploy and PyTorch start from identical
        # parameters, making the per-tensor grad comparison meaningful.
        init_map = {
            pytorch_param_to_onnx(name): p.detach().cpu().numpy().astype(np.float32)
            for name, p in pt_model.named_parameters()
        }
        # Buffers (BN running stats, etc.) — PyTorch keeps them in state_dict
        # but not in named_parameters(); the ONNX graph references them as
        # graph inputs, so we need their current values too.
        for name, buf in pt_model.named_buffers():
            init_map[pytorch_param_to_onnx(name)] = buf.detach().cpu().numpy().astype(np.float32)
        print(
            f"   network_infer.onnx absent → using PyTorch fresh weights "
            f"({len(init_map)} param/buffer tensors) as ground truth"
        )

    input_shape = exporter.get_input_shape()
    # Decide loss type by inspecting graph inputs: if there is an int64 input,
    # treat it as classification labels; otherwise MSE on a synthetic target.
    in_specs = graph_input_specs(network_path)
    has_int64 = any(et == TensorProto.INT64 for _, et, _ in in_specs)
    num_classes = exporter.config.get("num_classes", 2) if exporter.config else 2

    if has_int64:
        test_input_np, labels_np = synthesize_inputs(input_shape, num_classes, seed)
        target_for_loss_np = labels_np
    else:
        test_input_np = synthesize_mse_target(input_shape, seed=seed - 1)
        labels_np = synthesize_mse_target(input_shape, seed=seed)
        target_for_loss_np = labels_np
    print(
        f"   test_input shape={test_input_np.shape}  labels shape={labels_np.shape}  "
        f"loss={'CE' if has_int64 else 'MSE'}"
    )

    # Forward + backward
    pt_input = torch.from_numpy(test_input_np)
    pt_target = torch.from_numpy(target_for_loss_np)
    pt_input.requires_grad_(False)

    pt_model.zero_grad(set_to_none=False)
    pt_output = pt_model(pt_input)
    loss = build_pytorch_loss(pt_output, pt_target)
    loss.backward()

    # Capture per-param gradients keyed by ONNX initializer name.
    pt_grads: dict[str, np.ndarray] = {}
    for pt_name, p in pt_model.named_parameters():
        if p.grad is None:
            continue
        onnx_name = pytorch_param_to_onnx(pt_name)
        pt_grads[onnx_name] = p.grad.detach().cpu().numpy().astype(np.float32)
    print(f"   captured {len(pt_grads)} PyTorch gradient tensors")

    # ── Bake every non-data graph input (labels, params, grad_accs) into
    # initializers. Inference-style fixture: only the data tensor stays as a
    # graph input.
    print(f"   Baking non-data inputs into initializers (inference-style)...")
    data_input_name, baked = bake_inputs_as_initializers(
        network_path, init_map=init_map, labels_value=labels_np, input_shape=input_shape
    )
    print(f"   data input retained: '{data_input_name}'  ({len(baked)} inputs baked)")

    # ── inputs.npz: just the one data tensor.
    saved_inputs = {data_input_name: test_input_np}
    np.savez(src_dir / "inputs.npz", **saved_inputs)
    print(f"   ✅ inputs.npz  — 1 tensor ('{data_input_name}', shape={test_input_np.shape})")

    # ── outputs.npz: graph-output-name keyed (buffer names after promotion)
    out_names = graph_output_names(network_path)
    saved_outputs: dict[str, np.ndarray] = {}
    matched_grads = 0
    for out_name in out_names:
        if out_name.endswith(GRAD_OUT_SUFFIX):
            # InPlaceAccumulator's data_out — with the non-tiled binding
            # (Tiler.py:201) this gets written with the new gradient.
            param_onnx_name = out_name[: -len(GRAD_OUT_SUFFIX)]
            if param_onnx_name in pt_grads:
                saved_outputs[out_name] = pt_grads[param_onnx_name]
                matched_grads += 1
            else:
                ref_shape = init_map.get(param_onnx_name)
                ref_shape = ref_shape.shape if ref_shape is not None else ()
                saved_outputs[out_name] = np.zeros(ref_shape, dtype=np.float32)
        elif "loss" in out_name.lower():
            saved_outputs[out_name] = np.array(loss.detach().cpu().numpy(), dtype=np.float32)
        else:
            saved_outputs[out_name] = np.zeros((), dtype=np.float32)

    np.savez(src_dir / "outputs.npz", **saved_outputs)
    print(
        f"   ✅ outputs.npz — {len(saved_outputs)} tensors "
        f"(loss + {matched_grads} grads matched to PyTorch params, "
        f"keyed by graph output names)"
    )


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Convert an Onnx4Deeploy train-mode artifact dir into a "
        "single-step training-as-inference test fixture, using PyTorch autograd "
        "as the gradient reference."
    )
    parser.add_argument(
        "--model",
        required=True,
        help="Onnx4Deeploy model name (e.g. SimpleMLP, DSCNN, MobileNetV1, "
        "ResNet8, Autoencoder)",
    )
    parser.add_argument("src", type=Path, help="Source train artifact directory")
    parser.add_argument(
        "dst",
        type=Path,
        nargs="?",
        default=None,
        help="Destination directory (default: in-place overwrite)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for input + label generation",
    )
    args = parser.parse_args()

    src_dir: Path = args.src
    if not (src_dir / "network.onnx").exists():
        print(f"❌ Missing network.onnx in {src_dir}", file=sys.stderr)
        return 1

    if args.dst is None:
        dst_dir = src_dir
    else:
        dst_dir = args.dst
        if dst_dir.exists():
            shutil.rmtree(dst_dir)
        shutil.copytree(src_dir, dst_dir, symlinks=False)
        print(f"📋 Copied {src_dir} → {dst_dir}")

    print(f"\n🪛 Pinning bool inputs as constants in {dst_dir}/network.onnx ...")
    pinned = pin_bool_inputs(dst_dir / "network.onnx", value=True)
    print(f"   pinned: {pinned if pinned else '(none)'}")

    print(f"\n🪛 Fixing elem_type on '_grad.accumulation.out' outputs (BOOL→FLOAT) ...")
    fixed = fix_grad_output_dtypes(dst_dir / "network.onnx")
    print(f"   fixed {len(fixed)} graph outputs to elem_type=FLOAT")

    print(f"\n🧪 Regenerating inputs.npz / outputs.npz via PyTorch autograd ...")
    regenerate_test_data_pytorch(dst_dir, model_name=args.model, seed=args.seed)

    print(f"\n✅ Single-step fixture ready: {dst_dir}")
    print("   Run with: python3 deeployRunner_siracusa.py -t <dst_dir> -p Siracusa --cores=8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
