def load_init_map(onnx_path: Path) -> dict:
    """Load all initializers from an ONNX model into {name: ndarray}."""
    model = onnx.load(str(onnx_path))
    return {init.name: numpy_helper.to_array(init) for init in model.graph.initializer}


def pin_bool_inputs(onnx_path: Path, value: bool = True) -> list[str]:
    """
    Convert every tensor(bool) graph input into a constant initializer.

    Deeploy's PULP InPlaceAccumulatorV2 binding (Bindings.py:568) expects the
    third input to be ``uint8_t``, NOT bool — Deeploy maps the ONNX bool input
    to a uint8 buffer at codegen time.  When we pin the input as a constant we
    therefore have to emit it as uint8 (= 1 byte = bool semantics) so the
    downstream binding still picks the same checker.

    Returns the list of pinned input names.
    """
    model = onnx.load(str(onnx_path))
    pinned, kept = [], []
    for inp in model.graph.input:
        if inp.type.tensor_type.elem_type == TensorProto.BOOL:
            pinned.append(inp.name)
        else:
            kept.append(inp)
    if not pinned:
        return []
    del model.graph.input[:]
    model.graph.input.extend(kept)
    for name in pinned:
        const_arr = np.array([1 if value else 0], dtype=np.uint8)
        model.graph.initializer.append(numpy_helper.from_array(const_arr, name=name))
    onnx.save(model, str(onnx_path))
    return pinned


def graph_input_specs(onnx_path: Path) -> list[tuple[str, int, list[int]]]:
    """Return (name, elem_type, shape) per graph input in declaration order."""
    model = onnx.load(str(onnx_path))
    specs = []
    for inp in model.graph.input:
        shape = [d.dim_value for d in inp.type.tensor_type.shape.dim if d.dim_value > 0]
        specs.append((inp.name, inp.type.tensor_type.elem_type, shape))
    return specs


def graph_output_names(onnx_path: Path) -> list[str]:
    model = onnx.load(str(onnx_path))
    return [o.name for o in model.graph.output]


