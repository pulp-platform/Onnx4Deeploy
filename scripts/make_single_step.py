"""
make_single_step.py — Build a single-step training-as-inference test fixture
from an existing Onnx4Deeploy `train` artifact directory, using **PyTorch
autograd** as the gradient reference (no onnxruntime-training needed).

Use case
--------
Per-tensor gradient debugging. The standard `train` test runs N optimizer
steps and compares loss at the end — when MobileNet diverges at step 2 you
cannot tell which gradient is wrong. This tool rewires the same training
graph so it can be exercised by the inference runner (deeployRunner_*.py),
which compares every graph output (loss + each <param>_grad.accumulation.out)
against a PyTorch-autograd reference and prints per-tensor errors.

Two transformations on the source directory:
  1. network.onnx        — every `tensor(bool)` graph input (lazy_reset_grad)
                           is removed and re-added as a constant initializer
                           = [True], so each InPlaceAccumulator output equals
                           the pure batch dW (no historical accum).
  2. inputs.npz / outputs.npz — regenerated by:
       a) loading initial weights from network_infer.onnx initializers,
       b) instantiating the matching PyTorch exporter,
       c) loading those weights into the PyTorch model,
       d) running a single forward + loss + backward pass with a
          deterministic random batch (seed=42),
       e) writing inputs.npz with every non-bool graph input (data, labels,
          params, grad-accumulation buffers initialized to zeros) keyed by
          input name in graph order, and outputs.npz with the loss + each
          `<param>_grad.accumulation.out` keyed by graph output name.

Usage
-----
    python3 make_single_step.py --model SimpleMLP <src_train_dir> [<dst_dir>]

If <dst_dir> is omitted, the source dir is overwritten in place.

The model name must match an entry in Onnx4Deeploy.list_available_models()
(e.g. "SimpleMLP", "DSCNN", "MobileNetV1", "ResNet8", "Autoencoder").
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

import numpy as np
import onnx
import torch
from onnx import TensorProto, numpy_helper

# Make sure we can import Onnx4Deeploy.* and onnx4deeploy.*.
HERE = Path(__file__).resolve().parent
PROJECT_ROOT = HERE.parent
sys.path.insert(0, str(PROJECT_ROOT))


GRAD_ACC_SUFFIX = "_grad.accumulation.buffer"
GRAD_OUT_SUFFIX = "_grad.accumulation.out"
GRAD_VERIFIED_SUFFIX = "_grad.verified"


def bake_inputs_as_initializers(
    onnx_path: Path,
    init_map: dict,
    labels_value: np.ndarray,
    input_shape: tuple[int, ...],
) -> tuple[list[str], list[str]]:
    """
    Bake every graph input EXCEPT the data input into ``graph.initializer``.

    Inference-runner-style single-step: only the data tensor stays as a graph
    input; labels, all parameters, all ``_grad.accumulation.buffer`` tensors,
    and any other ctrl tensors are pinned as constants. This eliminates
    `testMVP.inferMinimalType` ambiguity (zero-init grad_acc would otherwise
    infer uint8) and reduces the test fixture to a single named tensor in
    ``inputs.npz``.

    Args:
        onnx_path:    Path to the network.onnx to modify in place.
        init_map:     {param_name: ndarray} of initial weight values.
        labels_value: int64 label tensor for this single batch.
        input_shape:  Shape of the data input — used to identify the one
                      graph input that should remain.

    Returns: (data_input_name, baked_input_names).
    """
    model = onnx.load(str(onnx_path))

    data_input_name: str = ""
    kept_inputs = []
    baked: list[str] = []

    for inp in model.graph.input:
        shape = [d.dim_value for d in inp.type.tensor_type.shape.dim if d.dim_value > 0]
        etype = inp.type.tensor_type.elem_type
        # Heuristic: the data input is the float32 tensor whose shape matches
        # the model's get_input_shape(). Everything else gets baked.
        is_data = (
            etype == TensorProto.FLOAT
            and tuple(shape) == tuple(input_shape)
            and inp.name not in init_map
            and not inp.name.endswith(GRAD_ACC_SUFFIX)
        )
        if is_data and not data_input_name:
            data_input_name = inp.name
            kept_inputs.append(inp)
            continue

        # Decide the constant value to bake.
        if etype == TensorProto.INT64:
            value = labels_value
        elif etype == TensorProto.BOOL:
            # lazy_reset_grad already pinned earlier; if not, default True.
            value = np.array([True], dtype=bool)
        elif inp.name in init_map:
            value = init_map[inp.name].astype(np.float32)
        elif inp.name.endswith(GRAD_ACC_SUFFIX):
            value = np.zeros(shape, dtype=np.float32)
        else:
            value = np.zeros(shape, dtype=np.float32)

        # Reshape if necessary so the initializer matches the declared shape.
        if shape and tuple(value.shape) != tuple(shape):
            try:
                value = value.reshape(shape)
            except Exception:
                pass

        model.graph.initializer.append(numpy_helper.from_array(value, name=inp.name))
        baked.append(inp.name)

    del model.graph.input[:]
    model.graph.input.extend(kept_inputs)
    onnx.save(model, str(onnx_path))

    if not data_input_name:
        raise RuntimeError(
            "bake_inputs_as_initializers: could not identify a unique data "
            "input. Check input_shape vs graph inputs."
        )
    return data_input_name, baked


def fix_grad_output_dtypes(onnx_path: Path) -> list[str]:
    """
    Fix elem_type on each ``<param>_grad.accumulation.out`` graph output.

    ORT's training-artifact emitter sometimes declares the InPlaceAccumulator
    output as TensorProto.BOOL (elem_type=9) even though the underlying
    buffer holds float32 gradients. Deeploy/GraphSurgeon then trip on this
    mistype downstream. Force elem_type=FLOAT for every grad output so the
    deployed graph types are consistent with the kernel's actual write.

    Companion to the change at ``Tiler.py:201`` that switches the
    ``InPlaceAccumulatorV2`` binding from ``PULPInPlaceAccumulatorV2TiledBindings``
    (writes only ``accum_buffer``) to ``PULPInPlaceAccumulatorV2Bindings``
    (writes BOTH ``accum_buffer`` AND ``data_out``). With that binding the
    ``_grad.accumulation.out`` graph outputs become populated, and the test
    harness can compare them to the PyTorch-autograd reference.

    Returns the list of fixed output names.
    """
    model = onnx.load(str(onnx_path))
    fixed: list[str] = []
    for o in model.graph.output:
        if o.name.endswith(GRAD_OUT_SUFFIX):
            o.type.tensor_type.elem_type = TensorProto.FLOAT
            fixed.append(o.name)
    if fixed:
        onnx.save(model, str(onnx_path))
    return fixed


